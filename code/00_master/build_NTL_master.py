def demote(text, by):
    """Shift markdown headings down by `by` levels (outside code fences)."""
    out, fence = [], False
    for line in text.splitlines():
        if line.startswith("```"):
            fence = not fence
        if not fence and re.match(r"#{1,6} ", line):
            line = "#" * by + line
        out.append(line)
    return "\n".join(out)


def src(path, by, title=None, code=False):
    p = f"{D}/{path}"
    if not os.path.exists(p):
        return f"\n(missing: `{path}`)\n"
    t = open(p).read().rstrip()
    head = f"\n{'#' * (by + 1)} {title}\n\nSource: `~/Desktop/{path}`\n\n" if title else f"\nSource: `~/Desktop/{path}`\n\n"
    return head + (f"```\n{t}\n```" if code else demote(t, by)) + "\n"


