def rows_of(p):
    try:
        with open(p, newline="") as fh:
            return sum(1 for _ in fh) - 1
    except Exception:
        return None


def size(n):
    return f"{n / 1e9:.2f} GB" if n >= 1e9 else f"{n / 1e6:.1f} MB" if n >= 1e6 else f"{n / 1e3:.0f} KB"


